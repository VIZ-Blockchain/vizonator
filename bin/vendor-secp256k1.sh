#!/bin/bash
# Re-vendors secp256k1.js from the official npm package @noble/secp256k1.
#
# The extension needs raw ECDH on secp256k1 (viz.min.js keeps its curve code private,
# it only exposes the memo scheme). @noble/secp256k1 is a single audited file with no
# dependencies; the only change we make is turning the ESM exports into one global,
# because both the Chrome service worker (importScripts) and the Firefox background
# page load classic scripts.
#
# Usage: bin/vendor-secp256k1.sh [version]   (default: the version pinned below)
set -e
VERSION="${1:-3.2.0}"
SHA256="2722e0b18b696cf6d3463ab10365f97f617fb651e85a7eeed8f12121a1077018"
DIR="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -sL "https://registry.npmjs.org/@noble/secp256k1/-/secp256k1-$VERSION.tgz" -o "$TMP/s.tgz"
GOT="$(sha256sum "$TMP/s.tgz" | cut -d' ' -f1)"
if [ "$VERSION" = "3.2.0" ] && [ "$GOT" != "$SHA256" ]; then
	echo "tarball sha256 mismatch: $GOT != $SHA256" >&2
	exit 1
fi
tar xzf "$TMP/s.tgz" -C "$TMP"

{
	echo "/* vendored from @noble/secp256k1@$VERSION (npm tarball sha256 $GOT)"
	echo "   generated by bin/vendor-secp256k1.sh — do not edit by hand */"
	echo "(function(root){"
	# ESM -> plain statements: the file has exactly two `export` lines (a const and the
	# final export list); dropping the keyword leaves valid script code.
	sed -e 's/^export const /const /' -e '/^export {/d' "$TMP/package/index.js"
	echo "root.nobleSecp256k1={getPublicKey:getPublicKey,getSharedSecret:getSharedSecret,Point:Point,etc:etc,utils:utils};"
	echo "})(typeof globalThis!=='undefined'?globalThis:self);"
} > "$DIR/secp256k1.js"

node -e "require('$DIR/secp256k1.js');if(typeof globalThis.nobleSecp256k1.getSharedSecret!=='function')throw new Error('vendored file does not expose getSharedSecret');"
echo "secp256k1.js re-vendored from @noble/secp256k1@$VERSION"
